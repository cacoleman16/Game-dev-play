# ---------------------------------------------------------------- text

def fmt(text):
    """Text with newlines (lines) and form feeds (pages) -> .string lines:
    a newline code after a page's first line, the scroll code after later
    lines, the page code between pages and $ at the end."""
    pages = text.strip('\n').split('\f')
    res = []
    for pi, page in enumerate(pages):
        lines = page.strip('\n').split('\n')
        for li, line in enumerate(lines):
            plain = re.sub(r'\{[A-Z_]+ ?[0-9A-Fx]*\}', '', line.replace('{PLAYER}', 'PLAYERNA'))
            if len(plain) > LINE_MAX:
                print('warning: long line (%d): %s' % (len(plain), line))
            if li == len(lines) - 1:
                end = '\\p' if pi < len(pages) - 1 else '$'
            else:
                end = '\\n' if li == 0 else '\\l'
            res.append('\t.string "%s%s"' % (line, end))
    return '\n'.join(res)


def T(label, text):
    return '%s::\n%s\n\n' % (label, fmt(text))


# ---------------------------------------------------------------- flags

def flag(name, comment=''):
    FLAGS.append((name, comment))
    return name


def write_flags():
    path = os.path.join(ROOT, 'include/constants/flags.h')
    s = open(path, encoding='utf-8').read()
    start, end = '// [QoL] Seika flags (generated by dev_scripts/seika/build.py)\n', '// [QoL] end of Seika flags\n'
    block = start
    for i, (n, c) in enumerate(FLAGS):
        block += '#define %-40s QOL_EXTRA_FLAG(0x%02X)%s\n' % (n, FIRST_FLAG + i, ('  // ' + c) if c else '')
    block += '#define QOL_SEIKA_FLAGS_END QOL_EXTRA_FLAG(0x%02X)\n' % (FIRST_FLAG + len(FLAGS))
    block += end
    if start in s:
        s = s[:s.index(start)] + block + s[s.index(end) + len(end):]
    else:
        anchor = '#define FLAG_QOL_HIDE_PALLET_MOM'
        i = s.index(anchor)
        i = s.index('\n', i) + 1
        s = s[:i] + block + s[i:]
    open(path, 'w', encoding='utf-8').write(s)


# ---------------------------------------------------------------- trainers

def trainer(const, name, cls, pic, gender, party, music='Male', ai='Smart Trainer', double=False, items=None):
    TRAINERS.append(dict(const=const, name=name, cls=cls, pic=pic, gender=gender, party=party.strip('\n'),
                         music=music, ai=ai, double=double, items=items))
    return const


def write_trainers():
    # IDs
    path = os.path.join(ROOT, 'include/constants/opponents_frlg.h')
    s = open(path, encoding='utf-8').read()
    start, end = '// [QoL] Seika trainers (generated by dev_scripts/seika/build.py)\n', '// [QoL] end of Seika trainers\n'
    block = start + ''.join('#define %-42s %d\n' % (t['const'], FIRST_TRAINER_ID + i) for i, t in enumerate(TRAINERS)) + end
    if start in s:
        s = s[:s.index(start)] + block + s[s.index(end) + len(end):]
    else:
        i = s.index('#define TRAINERS_COUNT_FRLG')
        s = s[:i] + block + '\n' + s[i:]
    count = FIRST_TRAINER_ID + len(TRAINERS)
    s = re.sub(r'#define TRAINERS_COUNT_FRLG\s+\d+.*', '#define TRAINERS_COUNT_FRLG                      %d // [QoL] was 624 (Team Nova and Seika added)' % count, s)
    assert count <= 768
    open(path, 'w', encoding='utf-8').write(s)
    # parties
    path = os.path.join(ROOT, 'src/data/trainers_frlg.party')
    s = open(path, encoding='utf-8').read()
    start, end = '/* [QoL] Seika region (generated by dev_scripts/seika/build.py) */\n', '/* [QoL] end of Seika region */\n'
    block = start
    for t in TRAINERS:
        block += '\n=== %s ===\nName: %s\nClass: %s\nPic: %s\nGender: %s\nMusic: %s\nDouble Battle: %s\nAI: %s\n' % (
            t['const'], t['name'], t['cls'], t['pic'], t['gender'], t['music'], 'Yes' if t['double'] else 'No', t['ai'])
        if t['items']:
            block += 'Items: %s\n' % t['items']
        party = t['party']
        if 'IVs:' not in party:  # post-game trainers: solid IVs by default
            party = re.sub(r'(Level: \d+)', r'\1\nIVs: 24 HP / 24 Atk / 24 Def / 24 SpA / 24 SpD / 24 Spe', party)
        block += '\n' + party + '\n'
    block += '\n' + end
    if start in s:
        s = s[:s.index(start)] + block + s[s.index(end) + len(end):]
    else:
        s = s.rstrip('\n') + '\n\n' + block
    open(path, 'w', encoding='utf-8').write(s)


def battle(label, const, intro, defeat, post, prefix):
    """A route/gym trainer: returns the scripts and texts."""
    return ('%s::\n\ttrainerbattle_single %s, %s_Text_%sIntro, %s_Text_%sDefeat\n'
            '\tmsgbox %s_Text_%sPost, MSGBOX_AUTOCLOSE\n\tend\n\n' % (label, const, prefix, label.split('_')[-1], prefix, label.split('_')[-1], prefix, label.split('_')[-1])
            + T('%s_Text_%sIntro' % (prefix, label.split('_')[-1]), intro)
            + T('%s_Text_%sDefeat' % (prefix, label.split('_')[-1]), defeat)
            + T('%s_Text_%sPost' % (prefix, label.split('_')[-1]), post))


# ---------------------------------------------------------------- maps

def add(m):
    MAPS.append(m)
    return m


def door(m, x, y, dest, dest_warp=0, elevation=3):
    """Add a warp to map m; returns its index."""
    m.warps.append(g.warp(x, y, dest, dest_warp, elevation))
    return len(m.warps) - 1


def npc(m, gfx, x, y, label, text, move='MOVEMENT_TYPE_FACE_DOWN', rx=1, ry=1, local_id=None, flag='0'):
    m.objects.append(g.obj(gfx, x, y, label, local_id=local_id, move=move, rx=rx, ry=ry, flag=flag))
    if text is not None:
        tl = label.replace('_EventScript_', '_Text_')
        m.scripts += '%s::\n\tmsgbox %s, MSGBOX_NPC\n\tend\n\n' % (label, tl) + T(tl, text)


def signpost(m, x, y, label, text, facing='BG_EVENT_PLAYER_FACING_ANY'):
    m.bgs.append(g.sign(x, y, label, facing))
    tl = label.replace('_EventScript_', '_Text_')
    m.scripts += '%s::\n\tmsgbox %s, MSGBOX_SIGN\n\tend\n\n' % (label, tl) + T(tl, text)


def pokecenter(town, mapsec, outside, out_warp, heal, music='MUS_RG_POKE_CENTER', npcs=()):
    """Pokémon Center 1F + 2F on Kanto's layouts. Returns the 1F map."""
    name1 = 'Seika_%s_PokemonCenter_1F' % town
    name2 = 'Seika_%s_PokemonCenter_2F' % town
    up = town.upper()
    id1 = 'MAP_SEIKA_%s_POKEMON_CENTER_1F' % up
    id2 = 'MAP_SEIKA_%s_POKEMON_CENTER_2F' % up
    f1 = add(g.MapDef(name1, id1, mapsec, 'LAYOUT_POKEMON_CENTER_1F_FRLG', music, 'MAP_TYPE_INDOOR',
                      'WEATHER_NONE', False, False, False))
    nurse = 'LOCALID_SEIKA_%s_NURSE' % up
    f1.objects.append(g.obj('OBJ_EVENT_GFX_NURSE_FRLG', 7, 2, '%s_EventScript_Nurse' % name1, local_id=nurse))
    for k in (6, 7, 8):
        door(f1, k, 8, outside.id, out_warp)
    door(f1, 1, 6, id2, 0, elevation=4)
    f1.map_scripts = [('MAP_SCRIPT_ON_TRANSITION', '%s_OnTransition' % name1),
                      ('MAP_SCRIPT_ON_RESUME', 'CableClub_OnResume')]
    f1.scripts = ('%s_OnTransition::\n\tsetrespawn %s\n\tend\n\n%s_EventScript_Nurse::\n\tlock\n\tfaceplayer\n'
                  '\tcall EventScript_PkmnCenterNurse_Frlg\n\trelease\n\tend\n\n' % (name1, heal, name1))
    for i, (gfx, x, y, text) in enumerate(npcs):
        npc(f1, gfx, x, y, '%s_EventScript_Npc%d' % (name1, i), text, 'MOVEMENT_TYPE_FACE_DOWN')
    f2 = add(g.MapDef(name2, id2, mapsec, 'LAYOUT_POKEMON_CENTER_2F_FRLG', music, 'MAP_TYPE_INDOOR',
                      'WEATHER_NONE', False, False, False))
    door(f2, 1, 6, id1, 3, elevation=4)
    door(f2, 5, 1, 'MAP_UNION_ROOM_FRLG', 0, elevation=0)
    door(f2, 9, 1, 'MAP_TRADE_CENTER_FRLG', 0, elevation=0)
    for gfx, x, scr in (('OBJ_EVENT_GFX_CABLE_CLUB_RECEPTIONIST', 5, 'Common_EventScript_UnionRoomAttendant'),
                        ('OBJ_EVENT_GFX_CABLE_CLUB_RECEPTIONIST', 9, 'Common_EventScript_WirelessClubAttendant'),
                        ('OBJ_EVENT_GFX_CABLE_CLUB_RECEPTIONIST', 13, 'Common_EventScript_DirectCornerAttendant')):
        f2.objects.append(g.obj(gfx, x, 2, scr))
    f2.map_scripts = [('MAP_SCRIPT_ON_FRAME_TABLE', 'CableClub_OnFrame'),
                      ('MAP_SCRIPT_ON_WARP_INTO_MAP_TABLE', 'CableClub_OnWarp'),
                      ('MAP_SCRIPT_ON_LOAD', 'CableClub_OnLoad'),
                      ('MAP_SCRIPT_ON_TRANSITION', 'CableClub_OnTransition')]
    HEALS.append({'id': heal, 'map': outside.id, 'x': outside.warps[out_warp]['x'],
                  'y': outside.warps[out_warp]['y'] + 1, 'respawn_map': id1, 'respawn_npc': nurse})
    return f1


def mart(town, mapsec, outside, out_warp, items, music='MUS_RG_POKE_CENTER', npcs=()):
    name = 'Seika_%s_Mart' % town
    mid = 'MAP_SEIKA_%s_MART' % town.upper()
    m = add(g.MapDef(name, mid, mapsec, 'LAYOUT_MART_FRLG', music, 'MAP_TYPE_INDOOR', 'WEATHER_NONE', False, False, False))
    for k in (3, 4, 5):
        door(m, k, 7, outside.id, out_warp)
    m.objects.append(g.obj('OBJ_EVENT_GFX_CLERK', 2, 3, '%s_EventScript_Clerk' % name, move='MOVEMENT_TYPE_FACE_RIGHT'))
    m.scripts = ('%s_EventScript_Clerk::\n\tlock\n\tfaceplayer\n\tmessage gText_HowMayIServeYou\n\twaitmessage\n'
                 '\tpokemart %s_Items\n\tmsgbox gText_PleaseComeAgain\n\trelease\n\tend\n\n\t.align 2\n%s_Items::\n'
                 % (name, name, name) + ''.join('\t.2byte %s\n' % it for it in items) + '\t.2byte ITEM_NONE\n\trelease\n\tend\n\n')
    for i, (gfx, x, y, text) in enumerate(npcs):
        npc(m, gfx, x, y, '%s_EventScript_Npc%d' % (name, i), text, 'MOVEMENT_TYPE_WANDER_AROUND')
    return m


def house(town, n, mapsec, outside, out_warp, music, npcs, layout='LAYOUT_HOUSE1_FRLG'):
    name = 'Seika_%s_House%d' % (town, n)
    mid = 'MAP_SEIKA_%s_HOUSE%d' % (town.upper(), n)
    m = add(g.MapDef(name, mid, mapsec, layout, music, 'MAP_TYPE_INDOOR', 'WEATHER_NONE', False, False, False))
    for k in (3, 4, 5):
        door(m, k, 7, outside.id, out_warp)
    for i, n2 in enumerate(npcs):
        gfx, x, y, text = n2[:4]
        move = n2[4] if len(n2) > 4 else 'MOVEMENT_TYPE_FACE_DOWN'
        npc(m, gfx, x, y, '%s_EventScript_Npc%d' % (name, i), text, move)
    return m


def wild(map_id, label, land=None, water=None, fishing=None, rate=20):
    e = {'map': map_id, 'base_label': label}
    if land:
        e['land_mons'] = {'encounter_rate': rate, 'mons': [
            {'min_level': lo, 'max_level': hi, 'species': 'SPECIES_' + sp} for sp, lo, hi in land]}
        assert len(land) == 12, label
    if water:
        e['water_mons'] = {'encounter_rate': 4, 'mons': [
            {'min_level': lo, 'max_level': hi, 'species': 'SPECIES_' + sp} for sp, lo, hi in water]}
        assert len(water) == 5, label
    if fishing:
        e['fishing_mons'] = {'encounter_rate': 20, 'mons': [
            {'min_level': lo, 'max_level': hi, 'species': 'SPECIES_' + sp} for sp, lo, hi in fishing]}
        assert len(fishing) == 10, label
    WILD.append(e)


