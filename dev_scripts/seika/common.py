def build_at(canvas, m, stamp, x, y, dest, dest_warp=0):
    """Stamp a building and add the warp at its door. Returns the warp index."""
    lid, sx, sy, w, h, dx, dy = stamp
    canvas.stamp(lid, sx, sy, w, h, x, y)
    return door(m, x + dx, y + dy, dest, dest_warp)
