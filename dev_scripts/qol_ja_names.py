#!/usr/bin/env python3
"""[QoL] Generate src/data/text/qol_ja_names.h: official Japanese (kana) names
for Pokemon, moves, items, abilities and types, from PokeAPI's data
(https://github.com/PokeAPI/pokeapi, data/v2/csv, language 1 = ja-Hrkt).

Download the CSVs into a folder first:
  for f in pokemon_species_names moves move_names items item_names abilities \\
           ability_names types type_names natures nature_names; do
    curl -O https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/$f.csv
  done
then run from the repo root:
  python3 dev_scripts/qol_ja_names.py <csv folder>

It also writes text/ja/src/pokemon.json (nature names, applied to
src/pokemon.c by dev_scripts/qol_japanese.py apply).
"""
import csv
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from qol_japanese import ALLOWED, normalize  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JA_KANA = '1'

def read_names(folder, file, idcol):
    out = {}
    with open(os.path.join(folder, file), encoding='utf-8') as f:
        for r in csv.DictReader(f):
            if r['local_language_id'] == JA_KANA:
                out[r[idcol]] = r['name']
    return out

def read_identifiers(folder, file):
    with open(os.path.join(folder, file), encoding='utf-8') as f:
        return {r['id']: r['identifier'] for r in csv.DictReader(f)}

def constants(header, prefix):
    src = open(os.path.join(ROOT, header), encoding='utf-8').read()
    return set(re.findall(r'\b(%s[A-Z0-9_]+)\b' % prefix, src))

def to_constant(prefix, identifier):
    return prefix + re.sub(r'[^A-Z0-9]+', '_', identifier.upper()).strip('_')

SPECIAL = {
    'MOVE_VICE_GRIP': 'MOVE_VISE_GRIP',
}

def clean(name):
    name = normalize(name).replace('★', '').strip()
    bad = [c for c in name if c not in ALLOWED]
    return None if bad else name

def emit(lines, cname, size, entries):
    lines.append('static const u8 *const %s[%s] =' % (cname, size))
    lines.append('{')
    for key, name in entries:
        lines.append('    [%s] = COMPOUND_STRING("%s"),' % (key, name))
    lines.append('};')
    lines.append('')

def main():
    folder = sys.argv[1]
    lines = ['// [QoL] Japanese names, generated by dev_scripts/qol_ja_names.py from PokeAPI', '// data (ja-Hrkt). Do not edit by hand.', '',
             '// Some constants are aliases of others (same ID); the later name wins.',
             '#pragma GCC diagnostic ignored "-Woverride-init"', '']
    skipped = []

    # Pokemon, by national Pokedex number.
    species = read_names(folder, 'pokemon_species_names.csv', 'pokemon_species_id')
    entries = []
    for num in sorted(species, key=int):
        name = clean(species[num])
        if name is None:
            skipped.append(('species', num, species[num]))
            continue
        entries.append((num, name))
    emit(lines, 'sJaSpeciesNames', 'NATIONAL_DEX_COUNT + 1', [(k, v) for k, v in entries if int(k) <= 1025])

    def by_constant(kind, ids_file, names_file, idcol, prefix, header, cname, size):
        ids = read_identifiers(folder, ids_file)
        names = read_names(folder, names_file, idcol)
        known = constants(header, prefix)
        out, seen = [], set()
        for i, ident in ids.items():
            if i not in names:
                continue
            const = to_constant(prefix, ident)
            const = SPECIAL.get(const, const)
            if const not in known or const in seen:
                continue
            name = clean(names[i])
            if name is None:
                skipped.append((kind, ident, names[i]))
                continue
            seen.add(const)
            out.append((const, name))
        emit(lines, cname, size, out)
        return len(out)

    n_moves = by_constant('move', 'moves.csv', 'move_names.csv', 'move_id', 'MOVE_',
                          'include/constants/moves.h', 'sJaMoveNames', 'MOVES_COUNT_ALL')
    n_items = by_constant('item', 'items.csv', 'item_names.csv', 'item_id', 'ITEM_',
                          'include/constants/items.h', 'sJaItemNames', 'ITEMS_COUNT')
    n_abil = by_constant('ability', 'abilities.csv', 'ability_names.csv', 'ability_id', 'ABILITY_',
                         'include/constants/abilities.h', 'sJaAbilityNames', 'ABILITIES_COUNT')
    n_types = by_constant('type', 'types.csv', 'type_names.csv', 'type_id', 'TYPE_',
                          'include/constants/pokemon.h', 'sJaTypeNames', 'NUMBER_OF_MON_TYPES')

    out = os.path.join(ROOT, 'src/data/text/qol_ja_names.h')
    open(out, 'w', encoding='utf-8').write('\n'.join(lines))

    # Nature names are pointers in src/pokemon.c, so they get inline alternates.
    natures = read_identifiers(folder, 'natures.csv')
    nnames = read_names(folder, 'nature_names.csv', 'nature_id')
    nat = {}
    for i, ident in natures.items():
        if i in nnames and clean(nnames[i]):
            nat[ident.capitalize()] = clean(nnames[i])
    path = os.path.join(ROOT, 'text/ja/src/pokemon.json')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    existing = json.load(open(path, encoding='utf-8')) if os.path.exists(path) else {}
    existing.update(nat)
    json.dump(existing, open(path, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

    print('species %d, moves %d, items %d, abilities %d, types %d, natures %d' % (
        len(entries), n_moves, n_items, n_abil, n_types, len(nat)))
    for s in skipped:
        print('skipped', s)

if __name__ == '__main__':
    main()
