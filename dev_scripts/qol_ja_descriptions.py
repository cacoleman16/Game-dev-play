#!/usr/bin/env python3
"""[QoL] Generate src/data/text/qol_ja_descriptions.h: Japanese (kana) Pokedex
entries and categories, and move, item and ability descriptions.

Source: PokeAPI's official Japanese flavor text (ja-Hrkt, newest game that has
it), rewrapped for this game's windows. Text that doesn't fit its window is
listed in text/ja/descriptions_todo.json; shorter versions go in
text/ja/descriptions.json ({"MOVE_POUND": "...", "ITEM_POTION": "...",
"ABILITY_STENCH": "...", "DEX_25": "..."}), which always wins.

Check a JSON of shortened texts:  python3 dev_scripts/qol_ja_descriptions.py --check FILE.json

Usage (from the repo root, after downloading the PokeAPI CSVs, see
dev_scripts/qol_ja_names.py, plus move_flavor_text, item_flavor_text,
ability_flavor_text and pokemon_species_flavor_text):
  python3 dev_scripts/qol_ja_descriptions.py <csv folder>
"""
import csv
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from qol_japanese import ALLOWED, normalize  # noqa: E402
from qol_ja_names import read_identifiers, constants, to_constant, SPECIAL  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OVERRIDES = os.path.join(ROOT, 'text/ja/descriptions.json')
TODO = os.path.join(ROOT, 'text/ja/descriptions_todo.json')

# (characters per line, lines) for each window
FIT = {
    'DEX': (25, 4),      # Pokedex entry
    'MOVE': (19, 2),     # summary screen move description
    'ITEM': (13, 3),     # bag description
    'ABILITY': (18, 1),  # summary screen ability description
}

def newest_flavor(folder, file, idcol, vercol):
    best = {}
    with open(os.path.join(folder, file), encoding='utf-8') as f:
        for r in csv.DictReader(f):
            if r['language_id'] != '1':
                continue
            # The newest games replace removed moves/items with a "can't be
            # used" note; use an older description instead.
            if 'つかえません' in r['flavor_text'] or 'つかえない' in r['flavor_text']:
                continue
            v = int(r[vercol])
            if r[idcol] not in best or v > best[r[idcol]][0]:
                best[r[idcol]] = (v, r['flavor_text'])
    return {k: v[1] for k, v in best.items()}

def flatten(text):
    text = normalize(text.replace('\n', '　').replace('\x0c', '　'))
    text = re.sub('[ 　]+', '　', text).strip('　')
    return text

def wrap(text, width, max_lines):
    """Greedy wrap on spaces; None if it doesn't fit or has unsupported characters."""
    if any(c not in ALLOWED for c in text):
        return None
    lines, cur = [], ''
    for word in text.split('　'):
        if len(word) > width:
            return None
        if cur and len(cur) + 1 + len(word) > width:
            lines.append(cur)
            cur = word
        else:
            cur = word if not cur else cur + '　' + word
    if cur:
        lines.append(cur)
    if len(lines) > max_lines:
        return None
    return '\\n'.join(lines)

def c_entry(key, text):
    return '    [%s] = COMPOUND_STRING("%s"),' % (key, text)

def check(path):
    """Report descriptions in a JSON file that don't fit their window."""
    data = json.load(open(path, encoding='utf-8'))
    bad = 0
    for key, text in data.items():
        kind = key.split('_')[0]
        width, nlines = FIT.get(kind, (0, 0))
        flat = flatten(text)
        wrong = sorted(set(c for c in flat if c not in ALLOWED))
        if wrong:
            print('%s: characters not in the font: %s' % (key, ''.join(wrong)))
            bad += 1
        elif wrap(flat, width, nlines) is None:
            print('%s: does not fit %d lines of %d characters (words longer than a line count too): %s' % (key, nlines, width, flat))
            bad += 1
    print('%d problem(s)' % bad)
    return 1 if bad else 0

def main():
    if sys.argv[1] == '--check':
        sys.exit(check(sys.argv[2]))
    folder = sys.argv[1]
    overrides = {}
    for extra in sorted(os.listdir(os.path.dirname(OVERRIDES))):
        if extra.startswith('descriptions') and extra.endswith('.json') and extra != os.path.basename(TODO):
            overrides.update(json.load(open(os.path.join(os.path.dirname(OVERRIDES), extra), encoding='utf-8')))
    todo = {}
    out = ['// [QoL] Japanese descriptions, generated by dev_scripts/qol_ja_descriptions.py',
           '// from PokeAPI data (ja-Hrkt) and text/ja/descriptions.json. Do not edit by hand.', '',
           '#pragma GCC diagnostic ignored "-Woverride-init"', '']

    def table(kind, cname, size, items):
        width, nlines = FIT[kind]
        out.append('static const u8 *const %s[%s] =' % (cname, size))
        out.append('{')
        n = 0
        for key, official in items:
            text = None
            if key in overrides:
                text = wrap(flatten(overrides[key]), width, nlines)
                if text is None:
                    print('override does not fit: %s' % key)
            if text is None and official:
                text = wrap(flatten(official), width, nlines)
                if text is None:
                    todo[key] = flatten(official)
            if text:
                out.append(c_entry(key if not key.startswith('DEX_') else key[4:], text))
                n += 1
        out.append('};')
        out.append('')
        return n

    # Pokedex entries and categories, by national dex number.
    dex = newest_flavor(folder, 'pokemon_species_flavor_text.csv', 'species_id', 'version_id')
    n_dex = table('DEX', 'sJaPokedexText', 'NATIONAL_DEX_COUNT + 1',
                  [('DEX_%s' % k, v) for k, v in sorted(dex.items(), key=lambda x: int(x[0])) if int(k) <= 1025])
    genus = {}
    with open(os.path.join(folder, 'pokemon_species_names.csv'), encoding='utf-8') as f:
        for r in csv.DictReader(f):
            if r['local_language_id'] == '1' and r['genus']:
                g = flatten(r['genus'])
                if g.endswith('ポケモン'):
                    g = g[:-len('ポケモン')]
                g = g.strip('　')
                if g and all(c in ALLOWED for c in g) and len(g) <= 12 and int(r['pokemon_species_id']) <= 1025:
                    genus[r['pokemon_species_id']] = g
    out.append('static const u8 *const sJaCategoryNames[NATIONAL_DEX_COUNT + 1] =')
    out.append('{')
    for k in sorted(genus, key=int):
        out.append(c_entry(k, genus[k]))
    out.append('};')
    out.append('')

    def by_constant(file, idcol, ids_file, prefix, header):
        ids = read_identifiers(folder, ids_file)
        known = constants(header, prefix)
        flav = newest_flavor(folder, file, idcol, 'version_group_id')
        items = []
        for i, ident in ids.items():
            const = SPECIAL.get(to_constant(prefix, ident), to_constant(prefix, ident))
            if const in known:
                items.append((const, flav.get(i)))
        return items

    n_moves = table('MOVE', 'sJaMoveDescriptions', 'MOVES_COUNT_ALL',
                    by_constant('move_flavor_text.csv', 'move_id', 'moves.csv', 'MOVE_', 'include/constants/moves.h'))
    n_items = table('ITEM', 'sJaItemDescriptions', 'ITEMS_COUNT',
                    by_constant('item_flavor_text.csv', 'item_id', 'items.csv', 'ITEM_', 'include/constants/items.h'))
    n_abil = table('ABILITY', 'sJaAbilityDescriptions', 'ABILITIES_COUNT',
                   by_constant('ability_flavor_text.csv', 'ability_id', 'abilities.csv', 'ABILITY_', 'include/constants/abilities.h'))

    open(os.path.join(ROOT, 'src/data/text/qol_ja_descriptions.h'), 'w', encoding='utf-8').write('\n'.join(out))
    json.dump(todo, open(TODO, 'w', encoding='utf-8'), ensure_ascii=False, indent=1, sort_keys=True)
    print('dex %d, categories %d, moves %d, items %d, abilities %d; %d need a shorter text (%s)' % (
        n_dex, len(genus), n_moves, n_items, n_abil, len(todo), os.path.relpath(TODO, ROOT)))

if __name__ == '__main__':
    main()
